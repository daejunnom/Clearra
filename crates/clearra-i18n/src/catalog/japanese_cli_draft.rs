#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    fn placeholders(value: &str) -> Vec<&str> {
        let mut result = value
            .split('{')
            .skip(1)
            .filter_map(|suffix| suffix.split_once('}').map(|(key, _)| key))
            .collect::<Vec<_>>();
        result.sort_unstable();
        result
    }

    #[test]
    fn templates_preserve_placeholders_and_never_fall_back_to_english() {
        let mut sources = BTreeSet::new();
        for (english, japanese) in MESSAGES {
            assert!(sources.insert(*english), "duplicate template: {english}");
            assert_ne!(english, japanese);
            assert_eq!(placeholders(english), placeholders(japanese), "{english}");
            assert_eq!(get(english), Some(*japanese));
        }
        assert_eq!(get("unreviewed source template"), None);
        assert!(!crate::LanguageId::Ja.is_released());
    }
}
