#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AppResultKind {
    Pc,
    Scenario,
    Path,
    Percent,
    Setup,
    BuildProbability,
    Damage,
    SpinFinder,
    Ren,
    SpinStructure,
    Cover,
    Rules,
    Scoring,
    Convert,
    Continue,
    Verify,
    VerifyKicks,
    Sequence,
    SequenceDependencies,
    Parity,
    Fumen,
    Render,
    ToGray,
    Mirror,
}

impl AppResultKind {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Pc => "pc",
            Self::Scenario => "pc-scenario",
            Self::Path => "path",
            Self::Percent => "percent",
            Self::Setup => "setup",
            Self::BuildProbability => "build-probability",
            Self::Damage => "damage",
            Self::SpinFinder => "spin-finder",
            Self::Ren => "ren",
            Self::SpinStructure => "spin-structure",
            Self::Cover => "build_coverage",
            Self::Rules => "rules",
            Self::Scoring => "scoring",
            Self::Convert => "convert",
            Self::Continue => "continue",
            Self::Verify => "verify",
            Self::VerifyKicks => "verify-kicks",
            Self::Sequence => "sequence",
            Self::SequenceDependencies => "sequence-dependencies",
            Self::Parity => "parity",
            Self::Fumen => "fumen",
            Self::Render => "render",
            Self::ToGray => "to-gray",
            Self::Mirror => "mirror",
        }
    }
}
